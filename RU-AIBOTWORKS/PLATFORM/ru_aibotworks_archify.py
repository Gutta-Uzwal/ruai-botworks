# ─────────────────────────── SVG rendering ───────────────────────────

def render_node(n: dict) -> str:
    x, y, w, h = node_box(n)
    kind = n["type"]
    cx = x + w / 2
    label, sub, tag = n["label"], n.get("sublabel"), n.get("tag")
    aria = f"Focus {label}" + (f", {sub}" if sub else "")
    title = " · ".join([p for p in (label, sub, tag) if p])
    rows = [f'<text data-node-label="" data-detail-anchor="" x="{cx}" y="{y + 25}" '
            f'class="t-primary" font-size="11" font-weight="600" text-anchor="middle">{e(label)}</text>']
    if sub:
        rows.append(f'<text data-detail="context" x="{cx}" y="{y + 40}" class="t-muted" '
                    f'font-size="9" text-anchor="middle">{e(sub)}</text>')
    if tag:
        rows.append(f'<text data-detail="fine" x="{cx}" y="{y + (52 if h > 58 else 50)}" '
                    f'class="t-{kind}" font-size="7" text-anchor="middle">{e(tag)}</text>')
    return (
        f'\n        <g id="node-{e(n["id"])}" data-node-id="{e(n["id"])}" '
        f'data-node-label="{e(label)}" tabindex="0" role="button" aria-label="{e(aria)}" '
        f'aria-pressed="false" data-node-kind="{kind}"'
        + (f' data-node-sublabel="{e(sub)}"' if sub else "")
        + (f' data-node-tag="{e(tag)}"' if tag else "")
        + '>\n'
        f'          <title>{e(title)}</title>\n'
        f'          <rect x="{x}" y="{y}" width="{w}" height="{h}" rx="6" class="c-mask"/>\n'
        f'          <rect x="{x}" y="{y}" width="{w}" height="{h}" rx="6" class="c-{kind}" stroke-width="1.5"/>\n'
        f'          <g aria-hidden="true" data-semantic-sigil="{kind}" class="semantic-sigil s-{kind}" '
        f'transform="translate({x + 6} {y + 6}) scale(0.6875)">{SIGILS[kind]}</g>\n'
        f'          ' + "\n          ".join(rows) + '\n        </g>'
    )


def render_edge(con: dict, key: int) -> str:
    cls, marker, _, width = VARIANT[con["variant"]]
    pts = con["points"]
    points_attr = ";".join(f"{px},{py}" for px, py in pts)
    return (
        f'\n        <path data-edge-from="{e(con["from"])}" data-edge-to="{e(con["to"])}"'
        + (f' data-edge-label="{e(con["label"])}"' if con.get("label") else "")
        + f' data-edge-key="{key}" data-edge-id="{e(con["id"])}" '
        f'data-composition-points="{points_attr}" d="{elbow(pts)}" class="{cls}" '
        f'stroke-width="{width}" marker-end="url(#{marker})"/>'
    )


def render_edge_label(con: dict, key: int) -> str:
    if not con.get("label"):
        return ""
    _, _, text_cls, _ = VARIANT[con["variant"]]
    mx, my = midpoint(con["points"])
    text = con["label"]
    width = len(text) * 4.8 + 10
    return (
        f'\n        <g data-detail="context" data-edge-from="{e(con["from"])}" '
        f'data-edge-to="{e(con["to"])}" data-edge-label="{e(text)}" data-edge-key="{key}" '
        f'data-edge-id="{e(con["id"])}">\n'
        f'          <rect x="{mx - width / 2:.1f}" y="{my - 7:.1f}" width="{width:.1f}" '
        f'height="14" rx="3" class="c-mask"/>\n'
        f'          <text x="{mx:.1f}" y="{my + 3:.1f}" class="{text_cls}" font-size="8" '
        f'text-anchor="middle">{e(text)}</text>\n        </g>'
    )



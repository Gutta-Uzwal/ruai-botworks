def elbow(points: list[tuple[float, float]], radius: float = 8) -> str:
    """Rounded orthogonal polyline, matching archify's path style."""
    if len(points) < 2:
        return ""
    if len(points) == 2:
        return f"M {points[0][0]} {points[0][1]} L {points[1][0]} {points[1][1]}"
    out = [f"M {points[0][0]} {points[0][1]}"]
    for i in range(1, len(points) - 1):
        px, py = points[i - 1]
        cx, cy = points[i]
        nx, ny = points[i + 1]
        r = min(radius, abs(cx - px) / 2 or radius, abs(cy - py) / 2 or radius,
                abs(nx - cx) / 2 or radius, abs(ny - cy) / 2 or radius)
        ix = cx - r if nx > cx or (nx == cx and px < cx) else cx + r
        iy = cy - r if ny > cy or (ny == cy and py < cy) else cy + r
        if px == cx:                       # arriving vertically
            out.append(f"L {cx} {cy - r if cy > py else cy + r}")
            out.append(f"Q {cx} {cy} {cx + r if nx > cx else cx - r} {cy}")
        else:                              # arriving horizontally
            out.append(f"L {cx - r if cx > px else cx + r} {cy}")
            out.append(f"Q {cx} {cy} {cx} {cy + r if ny > cy else cy - r}")
    out.append(f"L {points[-1][0]} {points[-1][1]}")
    return " ".join(out)


def midpoint(points: list[tuple[float, float]]) -> tuple[float, float]:
    """Midpoint of the longest straight run — where a label sits legibly."""
    best, span = points[0], -1.0
    for (x1, y1), (x2, y2) in zip(points, points[1:]):
        length = abs(x2 - x1) + abs(y2 - y1)
        if length > span:
            span, best = length, ((x1 + x2) / 2, (y1 + y2) / 2)
    return best


